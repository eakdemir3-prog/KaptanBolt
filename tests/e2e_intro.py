# Giriş videosu: ilk açılışta oynar, Geç ile kapanır, bir daha gelmez; gemi ekranından tekrar izlenir
from playwright.sync_api import sync_playwright
res=[]
def check(n,c): res.append(bool(c)); print(("PASS " if c else "FAIL ")+n)
with sync_playwright() as p:
    b=p.chromium.launch(executable_path="/usr/bin/google-chrome",args=["--use-angle=swiftshader","--enable-unsafe-swiftshader","--autoplay-policy=no-user-gesture-required"])
    pg=b.new_page(viewport={"width":393,"height":873}); errs=[]; pg.on("pageerror",lambda e:errs.append(str(e)))
    pg.goto("http://localhost:4173/#intro"); pg.wait_for_timeout(3500)
    check("ilk açılışta video ekranı açık", pg.is_visible("#intro"))
    t=pg.evaluate("document.getElementById('introVid').currentTime")
    check("video oynuyor", t>0.5 and not pg.evaluate("document.getElementById('introVid').paused"))
    pg.screenshot(path="/tmp/shots/intro_play.png")
    pg.click("[data-act=introSkip]"); pg.wait_for_timeout(600)
    check("Geç ile kapandı, menü görünüyor", not pg.is_visible("#intro") and pg.evaluate("KB.screen")=="menu")
    check("introSeen ve storySeen kaydedildi", pg.evaluate("KB.data().introSeen && KB.data().storySeen"))
    pg.click("[data-act=continue]"); pg.wait_for_timeout(1200)
    check("bölüm 1 doğrudan açıldı (yazılı hikâye penceresi yok)", pg.evaluate("KB.screen")=="game" and pg.locator("#card [data-act=storyGo]").count()==0)
    pg.goto("http://localhost:4173/#intro"); pg.wait_for_timeout(2500)
    pg.evaluate("KB.data().introSeen=true; KB.data().storySeen=true")
    pg.reload(); pg.wait_for_timeout(2500)
    check("yeniden açılışta video gelmiyor", not pg.is_visible("#intro"))
    pg.click("[data-act=ship]"); pg.wait_for_timeout(400); pg.click("#card [data-act=story]"); pg.wait_for_timeout(1500)
    check("gemi ekranındaki Hikâye videoyu açıyor", pg.is_visible("#intro"))
    pg.keyboard.press("Escape"); pg.wait_for_timeout(600)
    check("geri tuşu videoyu kapatıp gemi ekranına dönüyor", not pg.is_visible("#intro") and pg.locator("#card .ship-grid").count()==1)
    check("hata yok", not errs); print(errs)
    b.close()
print(f"{sum(res)} geçti, {len(res)-sum(res)} kaldı")
