# Oyun ortasında çıkış: uyarı gelir, onaylanırsa 1 enerji düşer; hamle yapılmadan çıkış ücretsiz
from playwright.sync_api import sync_playwright
res=[]
def check(n,c): res.append(bool(c)); print(("PASS " if c else "FAIL ")+n)
KEY={"up":"ArrowUp","down":"ArrowDown","left":"ArrowLeft","right":"ArrowRight"}
with sync_playwright() as p:
    b=p.chromium.launch(executable_path="/usr/bin/google-chrome",args=["--no-sandbox","--use-angle=swiftshader","--enable-unsafe-swiftshader"])
    pg=b.new_page(viewport={"width":412,"height":915})
    errs=[]; pg.on("pageerror",lambda e:errs.append(str(e)))
    pg.goto("http://localhost:4173/"); pg.wait_for_timeout(1500)
    pg.evaluate("Object.assign(KB.data().seenTutorial,{keys:1}); KB.data().energy=5")
    idle=lambda: pg.wait_for_function("KB.idle()",timeout=15000)
    en=lambda: pg.evaluate("KB.data().energy")
    pg.evaluate("KB.start(6)"); pg.wait_for_timeout(1200)
    pg.evaluate("document.querySelector('.screen.on [data-act=back]').click()"); pg.wait_for_timeout(600)
    check("hamle yokken çıkış: uyarı yok, enerji aynı", pg.evaluate("KB.screen")=="map" and en()==5)
    pg.evaluate("KB.start(6)"); pg.wait_for_timeout(1200)
    pg.keyboard.press(KEY[pg.evaluate("KB.solve()")[0]]); idle()
    pg.evaluate("document.querySelector('.screen.on [data-act=back]').click()"); pg.wait_for_timeout(600)
    check("hamle sonrası çıkış: uyarı geldi", pg.locator("#card [data-act=leave]").count()==1)
    pg.screenshot(path="/tmp/shots/exit_warn.png")
    pg.click("#card [data-act=stay]"); pg.wait_for_timeout(400)
    check("Oyuna devam: oyunda kaldı, enerji aynı", pg.evaluate("KB.screen")=="game" and en()==5 and pg.evaluate("KB.state.status")=="play")
    pg.keyboard.press("Escape"); pg.wait_for_timeout(500)
    check("Android geri tuşu da uyarıyor", pg.locator("#card [data-act=leave]").count()==1)
    pg.click("#card [data-act=leave]"); pg.wait_for_timeout(700)
    check("Çık: haritaya döndü, 1 enerji düştü", pg.evaluate("KB.screen")=="map" and en()==4)
    pg.evaluate("KB.start(6)"); pg.wait_for_timeout(1200)
    pg.keyboard.press(KEY[pg.evaluate("KB.solve()")[0]]); idle()
    pg.click("[data-act=restart]"); pg.wait_for_timeout(500)
    pg.click("#card [data-act=leave]"); pg.wait_for_timeout(1200)
    check("Yarıda yeniden başla: 1 enerji düştü, bölüm baştan", en()==3 and pg.evaluate("KB.state.moves")==0)
    check("oyun ekranında ayrı geri al düğmesi yok", pg.locator("#undoBtn").count()==0)
    check("hata yok", not errs); print(errs)
    b.close()
print(f"{sum(res)} geçti, {len(res)-sum(res)} kaldı")
